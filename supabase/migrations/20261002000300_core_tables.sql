-- 0300 Core tables (Section 6). Identical schema in both country projects.
-- Money = *_minor bigint + currency char(3). Every table: created_at,
-- updated_at (trigger) and RLS enabled (policies in 0600).
set search_path = public, extensions;

-- profiles ---------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text,
  phone text,
  email text,
  photo_url text,
  language text not null default 'en',
  roles text[] not null default '{buyer}'
    check (roles <@ array['buyer','seller','admin']::text[]),
  active_mode text not null default 'buyer' check (active_mode in ('buyer','seller')),
  status text not null default 'active' check (status in ('active','suspended','banned','deleted')),
  suspended_until timestamptz,
  status_reason text,
  timezone text,
  notification_prefs jsonb not null default
    '{"mode":"instant","quiet_hours":{"start":"22:00","end":"07:00"},"push":true,"marketing":false}'::jsonb,
  is_review_account boolean not null default false,
  referral_code text unique default substr(md5(gen_random_uuid()::text), 1, 8),
  referred_by uuid references public.profiles(id) on delete set null,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

