-- updated_at triggers + RLS on every table ---------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array[
    'profiles','addresses','device_tokens','blocks','postal_codes','cities','categories',
    'category_keywords','sellers','seller_contacts','seller_categories','seller_documents',
    'seller_licences','entitlements','billing_events','requests','request_private',
    'request_media','quotes','quote_line_items','quote_revisions','quote_templates',
    'lead_states','chats','messages','orders','order_events','reviews','reports',
    'notifications','consents']
  loop
    perform private.add_updated_at_trigger(('public.' || t)::regclass);
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;
